"""Benchmark workflow entry point."""
from __future__ import annotations

from contextlib import contextmanager, redirect_stderr, redirect_stdout
from datetime import datetime
import json
from pathlib import Path
import sys

import baseline
from workflow_cli import parse_args
import workflow_runner as runner
import workflow_reports as reports

class _Tee:
    def __init__(self, stream, log):
        self.stream, self.log = stream, log

    def write(self, text):
        self.log.write(text)
        return self.stream.write(text)

    def flush(self):
        self.stream.flush()
        self.log.flush()

@contextmanager
def _tee_logs(path):
    """Restore streams and close the log even when execution fails."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with (
        path.open("w", encoding="utf-8", buffering=1) as log,
        redirect_stdout(_Tee(sys.stdout, log)),
        redirect_stderr(_Tee(sys.stderr, log)),
    ):
        try:
            yield
        finally:
            sys.stdout.flush()
            sys.stderr.flush()

def _baseline_slice(data, engines, datasets, mode):
    selected = {"metadata": data.get("metadata", {})}
    runs_source = baseline.loading_runs(data)
    selected["loadingRuns"] = [
        r for r in runs_source
        if r.get("engine") in engines and r.get("dataset") in datasets
    ]
    selected["queryRuns"] = [
        r for r in data.get("queryRuns", [])
        if r.get("engine") in engines and r.get("dataset") in datasets
    ]
    if mode == "load":
        selected["queryRuns"] = []
    elif mode == "query":
        selected["loadingRuns"] = []
    return selected

def _run_fresh(project, wrapper, input_dir, out_dir, stamp, config, engines):
    files = []
    runner.sync_local_corese_jar(project, engines, config.corese_local_path)
    dirs = runner.prepare_datasets(config.datasets, input_dir)
    runner.convert_datasets_for_run(wrapper, project, dirs, config.mode, config.formats)
    for index, batch in enumerate(runner.plan_gradle_batches(engines)):
        props = runner.gradle_props_for_batch(batch)
        runner.gradle_build(project, wrapper, props)
        for dataset in config.datasets:
            output = out_dir / "json" / f"{stamp}_{index}_{dataset}.json"
            runner.run_benchmark(project, wrapper, batch, output, dataset, dirs[dataset], config, props)
            if not output.is_file():
                raise RuntimeError(f"No fresh report generated by current run: {output}")
            reports.validate_single_report_dict(json.loads(output.read_text()), str(output))
            files.append(str(output))
    return files

def _execute(project, wrapper, input_dir, out_dir, stamp, config):
    partial = config.is_partial_formats
    if partial:
        print(f"[dev] Partial format subset ({','.join(config.formats)}): running fresh without baseline reuse or site/data export")
    data = baseline.load_baseline(config.baseline) if config.effective_reuse == "baseline" else {}
    expected = baseline.load_expected_v1_queries() if config.mode != "load" else {}
    plan = baseline.plan_engines(list(config.engines), list(config.datasets), data,
                                 expected_queries=expected,
                                 force_all=(config.effective_reuse == "none"),
                                 update_baseline=config.update_baseline)
    print(f"[plan] Reused: {plan.cached_engines}; fresh: {plan.fresh_engines}")
    files = []
    if plan.cached_engines:
        cached = out_dir / "json" / f"{stamp}_baseline.json"
        cached.write_text(json.dumps(_baseline_slice(data, plan.cached_engines, config.datasets, config.mode)))
        files.append(str(cached))
    if plan.fresh_engines:
        files.extend(_run_fresh(project, wrapper, input_dir, out_dir, stamp, config, plan.fresh_engines))
    if not files:
        raise RuntimeError("No valid report generated by current run")
    output = out_dir / "json" / f"{stamp}_report.json"
    reports.merge_json_files(files, str(output))
    reports.export_and_maybe_update_baseline(json.loads(output.read_text()), project, config)

def main(argv=None) -> int:
    config = parse_args(argv)
    project = Path(__file__).resolve().parents[1]
    input_dir, out_dir = runner.resolve_paths(project, config.data_dir)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    with _tee_logs(out_dir / "logs" / f"{stamp}.log"):
        runner.ensure_java_home()
        (out_dir / "json").mkdir(parents=True, exist_ok=True)
        wrapper = project / ("gradlew.bat" if sys.platform == "win32" else "gradlew")
        _execute(project, wrapper, input_dir, out_dir, stamp, config)
    return 0

if __name__ == "__main__":
    sys.exit(main())
